/** Текст пункта 1.3 о качестве работ */
export function qualityClause(subject?: string | null): string {
  const s = (subject || "").trim()
  const norms = NORMS[s]
  if (!norms) {
    return "Качество работ должно соответствовать действующим строительным нормам и правилам (СНиП), сводам правил (СП), государственным стандартам (ГОСТ) и техническим регламентам. При отсутствии конкретных требований качество определяется общепринятой практикой выполнения строительных и отделочных работ."
  }
  return `Качество работ должно соответствовать ${norms}, а также иным действующим сводам правил (СП), государственным стандартам (ГОСТ) и техническим регламентам, применимым к данному виду работ. При отсутствии конкретных требований качество определяется общепринятой практикой выполнения таких работ.`
}
