export function getServiceFaq(meta: ServiceLandingMeta): FaqEntry[] {
  const specific = SPECIFIC_FAQ[meta.category] || []
  const generic = GENERIC_FAQ(meta)
  const questions = new Set(specific.map((f) => f.question))
  return [...specific, ...generic.filter((f) => !questions.has(f.question))].slice(0, 6)
}
